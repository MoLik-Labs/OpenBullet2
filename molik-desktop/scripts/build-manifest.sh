#!/bin/sh
# rustup target add wasm32-unknown-unknown; run with Rust 1.88 for a reproducible build.
set -eu
cd "$(dirname "$0")/.."
x=$(mktemp -d);trap 'rm -rf "$x"' EXIT
rustc --edition 2021 --crate-type cdylib --target wasm32-unknown-unknown -C opt-level=z -C lto -C panic=abort -C strip=symbols manifest/lib.rs -o "$x/engine.wasm"
python3 - "$x/engine.wasm" <<'PY'
from pathlib import Path
import sys,base64
encoded = base64.b64encode(Path(sys.argv[1]).read_bytes()).decode()
Path('ui/manifest-engine.js').write_text('// Generated by scripts/build-manifest.sh; do not edit.\nconst manifestBytes = "' + encoded + '";\n')
PY
